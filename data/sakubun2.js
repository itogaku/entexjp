  const N = (ans, per = 20) => {
    const s = String(ans);
    return s.includes('\n') || s.startsWith('　')
      ? `（${KN(used(s, per))}マス・空きマスをふくむ）`
      : `（${KN(used(s, per))}字）`;
  };
