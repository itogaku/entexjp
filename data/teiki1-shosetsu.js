  const LVN = ['明るい', 'やや明るい', 'ふつう', 'やや暗い', '暗い'];
  function curve(rows) {
    const head = ['#'].concat(LVN.map((t) => '#' + t), ['#心情を表す言葉']);
    const body = rows.map(([s, lv, word, blankDot, blankWord]) => ['#' + s]
      .concat(LV.map((v) => (blankDot ? { len: 3.6, ans: v === lv ? '●' : '' } : v === lv ? '●' : '')))
      .concat([blankWord ? { len: 7, ans: word } : word]));
    return TBL([head].concat(body));
  }

