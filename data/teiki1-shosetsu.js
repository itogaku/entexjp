  const SUB = ['⑴', '⑵', '⑶', '⑷', '⑸', '⑹', '⑺', '⑻', '⑼', '⑽'];
  const mark = (t) => String(t).replace(/\{\{([^|}]+)\|([^}]*)\}\}/g, (_, s, l) => BO(s, l));
  const len = (s) => Array.from(String(s)).length;
  const HEAD = (t) => `<div class="round-h">${t}</div>`;
