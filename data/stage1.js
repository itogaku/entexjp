/* ステージ１　抽象と具体 */
(function () {
  const { B, K, L, G, S, CH, BO, GO, GRID, AIM, POINT, RULE, EX, Q, QC, HINT, PASS, TBL, FLOW, STEPS, KAI } = Yomi.h;
  const n = (s) => `<span class="sub-no">${s}</span>`;

  /* ---------------- 1-1 ---------------- */
  Yomi.register({
    id: '1-1', stage: 1, level: 2,
    title: '例の部分と考えの部分',
    sub: '文章の中で具体例と筆者の考えを見分ける',
    blocks: [
      AIM('説明的文章を、筆者の考え（広い言葉で書かれた部分）と、それを支える例（せまい言葉で書かれた部分）に分けて読みます。'),
      POINT('考えと例の組み立て', `
        <p>筆者は、考えだけでは読者が納得しにくいので、例をそえて説得します。よくある組み立ては次の形です。</p>
        ${FLOW([{ lbl: '広い', html: '筆者の考え' }, { con: '例をあげると' }, { lbl: 'せまい', html: '例（一つ〜三つ）' }, { con: 'このように' }, { lbl: '広い', html: '考えを言いかえる' }], 40)}
        ${TBL([
          ['#例が始まる合図', 'たとえば・例をあげると・〜がその一つだ・〜もある・また'],
          ['#考えにもどる合図', 'このように・要するに・つまり・こうして・〜のである'],
        ])}
        ${RULE('見分け方：その部分を消しても筆者の言いたいことが伝わるなら<b>例</b>。消すと伝わらなくなるなら<b>考え</b>。')}`),
      PASS({ title: '【文章Ａ】', nums: true, paras: [
        '植物は動けないかわりに、まわりの変化を感じ取って生きている。',
        'たとえば、アサガオは、夜の長さを感じて花を開く時刻を決めている。タンポポの花は、雨の日や夕方には閉じてしまう。また、ヒマワリのつぼみは、太陽の動きに合わせて向きを変える。',
        'このように、植物は、じっとしているように見えても、光や水の変化に細かく応えているのである。',
      ] }),
      Q('一', '文章Ａの②段落にあげられている例を、植物の名前で三つ書きましょう。', `
        <p class="indent mt">${B(7, 'アサガオ')}・${B(7, 'タンポポ')}・${B(7, 'ヒマワリ')}</p>`),
      Q('二', '①段落の「まわりの変化」は、③段落では何と言いかえられていますか。六字で抜き出しましょう。', `
        <p class="indent mt">${B(8, '光や水の変化')}</p>`),
      PASS({ title: '【文章Ｂ】', paras: [
        '同じ言葉でも、住む地域によって意味がちがうことがある。関西では「なおす」を「片づける」という意味で使い、「このおもちゃ、なおしといて」と言う。また、ある地方では「えらい」を「つかれた」という意味で使い、「今日は歩いてえらかった」と言う。言葉の意味は、使う土地によって変わるものなのだ。',
      ] }),
      Q('三', '文章Ｂについて答えましょう。', `
        <p class="hang mt">${n('⑴')}　例として取り上げられている言葉を二つ書きましょう。　${B(5, 'なおす')}・${B(5, 'えらい')}</p>
        <p class="hang">${n('⑵')}　筆者の考えが書かれた文が二つあります。そのうち、最後の文の初めの五字を書きましょう。</p>
        <p class="indent">${B(6, '言葉の意味')}</p>
        <p class="hang">${n('⑶')}　文章Ｂに加える例を、自分で考えて一つ書きましょう。</p>
        ${L(2, '（例）北海道では、手袋を「はく」と言い、「はめる」とは言わない人が多い。', 170)}`),
      HINT('<p>三⑵　句読点（、。）も一字と数えます。<br>三⑶　「ある地域で」「意味や使い方がちがう」の両方が入っているか確かめましょう。</p>'),
    ],
    kaisetsu: [
      KAI('一', 'アサガオ／タンポポ／ヒマワリ', '<p>②段落は「たとえば」で始まり、「また」で例を加えています。②段落を消しても、①と③で筆者の言いたいことは伝わります。</p>', '例の段落は、消しても言いたいことが残る'),
      KAI('二', '光や水の変化', '<p>①「まわりの変化を感じ取って」＝③「光や水の変化に細かく応えている」。①と③が筆者の考えで、②が例です。夜の長さ・太陽は「光」、雨は「水」にまとめられています。</p>'),
      KAI('三', '⑴なおす・えらい　⑵言葉の意味　⑶（例）北海道では、手袋を「はく」と言い、「はめる」とは言わない人が多い。', `
        <p>⑴関西の「なおす」と、ある地方の「えらい」の二つ。⑵最初の文「同じ言葉でも〜ちがうことがある」と、最後の文「言葉の意味は、使う土地によって変わるものなのだ」が考えの部分です。⑶「地域」と「意味・使い方のちがい」がそろっていれば正解です。</p>`,
        '筆者の言いたいことは、例の前後の広い言葉の文にある'),
    ],
  });

  /* ---------------- 1-2 ---------------- */
  Yomi.register({
    id: '1-2', stage: 1, level: 2,
    title: '練習：例の束をひと言でくくる',
    sub: '抽象化（文・文章）',
    blocks: [
      AIM('いくつかの例を、一つの言葉や一文にくくる練習をくり返します。'),
      POINT('ふり返り', `<p>①出来事を書き出す　②ちがう部分は消して、どれにも当てはまる言葉を探す　③組が分かれていれば、小さなくくり→大きなくくり。最後に、もとの物の名前が残っていないか確かめる。</p>`),
      Q('一', '次の文を「ひと言で：」の後に一文でまとめましょう。', `
        <p class="hang mt">${n('⑴')}　この町では、春は田んぼにカエルが鳴き、夏は川でホタルが飛び、秋は山が赤や黄色にそまる。</p>
        <p class="indent">ひと言で：${B(18, 'この町は、季節ごとの自然が豊かだ。')}</p>
        <p class="hang mt">${n('⑵')}　祖母は、すり切れたズボンにつぎを当て、ほつれたセーターを編み直し、短くなったえんぴつにはキャップをつけて使う。</p>
        <p class="indent">ひと言で：${B(18, '祖母は、物を最後まで大切に使う。')}</p>
        <p class="hang mt">${n('⑶')}　姉は、本番の前の晩には持ち物を三回確かめ、当日は一時間早く会場に着き、出番の前には必ず深呼吸をする。</p>
        <p class="indent">ひと言で：${B(18, '姉は、本番の前にしっかり準備をする。')}</p>
        <p class="hang mt">${n('⑷')}　この図書館は、絵本の部屋にくつをぬいで上がれるたたみを置き、文字の大きな本の棚を作り、夜の九時まで開いている。</p>
        <p class="indent">ひと言で：${B(18, 'この図書館は、いろいろな人が使いやすいように工夫している。')}</p>`),
      PASS({ title: '【本文】', nums: true, paras: [
        'ある小学校では、校庭の一角を、遊具も線も置かない「何もない場所」として残している。',
        '初めは、子どもたちもとまどっていた。しかし、やがて、落ち葉を集めて家を作ったり、石をならべて迷路を作ったりし始めた。木の枝一本から、新しい遊びのルールが生まれることもあった。',
        '遊び方の決まった道具がないからこそ、子どもたちは自分で遊びを考え出すようになったのである。',
      ] }),
      Q('二', '本文について答えましょう。', `
        <p class="hang mt">${n('⑴')}　②段落の例を、次の表に整理しましょう。</p>
        ${TBL([
          ['#使った物', '#子どもたちがしたこと'],
          ['落ち葉', { len: 11, ans: '家を作った' }],
          [{ len: 5, ans: '石' }, { len: 11, ans: '迷路を作った' }],
          ['木の枝', { len: 11, ans: '新しい遊びのルールを生んだ' }],
        ])}
        <p class="hang mt">${n('⑵')}　②段落の例に共通することを、③段落から十字で抜き出しましょう。</p>
        <p class="indent">${B(11, '自分で遊びを考え出す')}</p>`),
    ],
    kaisetsu: [
      KAI('一', '（例）⑴この町は、季節ごとの自然が豊かだ。　⑵祖母は、物を最後まで大切に使う。　⑶姉は、本番の前にしっかり準備をする。　⑷この図書館は、いろいろな人が使いやすいように工夫している。', '<p>⑴カエル・ホタル・紅葉→季節の自然。⑵ズボン・セーター・えんぴつ→物を大切に使う。⑶三つとも「本番に向けた準備」。⑷たたみは小さな子、大きな文字は目の弱い人、夜の開館は昼に働く人のための工夫です。</p>', 'ちがう部分は消し、どれにも当てはまる言葉でくくる'),
      KAI('二', '⑴表のとおり　⑵自分で遊びを考え出す', '<p>家・迷路・ルールは、どれも子どもたちが自分で作り出した遊びです。③段落の「自分で遊びを考え出す」が、その共通点を広い言葉で言ったものです。</p>', '→1-1　筆者の考えは例の前後'),
    ],
  });

  /* ---------------- 1-3 ---------------- */
  Yomi.register({
    id: '1-3', stage: 1, level: 3,
    title: '練習：その例は何のためにあるか',
    sub: '具体例の働き（記述）',
    blocks: [
      AIM('入試では「この例は何を説明するためにあげられているか」がよく問われます。例と、それが支えている筆者の考えを結びつけて書く練習です。'),
      POINT('例の働きを書く手順', `
        ${STEPS(['傍線の例を、自分でひと言にくくってみる。', 'そのひと言と同じ内容を、例の<b>前後</b>の広い言葉の文から探す。', '見つけた文の言葉を使い、例の中の物の名前を入れずに、指定の形に当てはめる。'])}`),
      PASS({ title: '【本文】', nums: true, paras: [
        '便利な道具は、私たちのできることを広げる。その一方で、もともと持っていた力を弱めることもある。',
        `${BO('カーナビを使って車を運転する人の中には、何度も通った道なのに、自分では道順を覚えていない人がいるという。', '①')}機械が道を教えてくれるので、自分で覚える必要がなくなったのである。`,
        '道具に任せた部分の力は、使わないうちに少しずつおとろえていく。だからこそ、どこまで道具に任せるかを、自分で決める必要があるのだ。',
      ] }),
      Q('一', '──線部①の例は、どのようなことを説明するためにあげられていますか。最も適切なものを一つ選びましょう。', `
        ${CH([
          'カーナビを使うと、車の運転が安全になるということ。',
          '道具に任せた部分の力は、使わないうちに弱まっていくということ。',
          '道順を覚えるのが苦手な人が、年々増えているということ。',
          '機械は、人間よりも正確に道を案内できるということ。',
        ], 'イ')}
        <p class="indent">${K('イ')}</p>`),
      Q('二', '──線部①の例の働きを、「〜ということを、カーナビの例で説明している。」の形に合うように、三十五字以内で書きましょう。', `
        ${G(35, '道具に任せた部分の力は、使わないうちに少しずつおとろえていく', 18)}
        <p class="indent">ということを、カーナビの例で説明している。</p>`),
      Q('三', '③段落の一文目に合う例を、自分で考えて一つ書きましょう。', `
        ${L(2, '（例）計算をいつも電卓に任せていると、暗算がだんだんおそくなる。', 170)}`),
    ],
    kaisetsu: [
      KAI('一', 'イ', '<p>例をひと言にくくると「覚えなくなった」。それと同じ内容が③段落の「道具に任せた部分の力は、使わないうちに少しずつおとろえていく」です。アは安全、エは正確さの話で、ずれています。</p>', '例の働き＝前後の広い言葉の文'),
      KAI('二', '（例）道具に任せた部分の力は、使わないうちに少しずつおとろえていく（三十字）', '<p>「カーナビ」「道順」などの例の中の言葉を使わずに書けているかがポイントです。「便利な道具は、もともと持っていた力を弱めることもある」（①段落）を使った答えも可。</p>'),
      KAI('三', '（例）計算をいつも電卓に任せていると、暗算がだんだんおそくなる。', '<p>「道具に任せる」と「その力がおとろえる」の両方が入っていれば正解です。「漢字を変換機能に任せていたら、手で書けなくなった」なども可。</p>'),
    ],
  });
})();
