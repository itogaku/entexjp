  /** 漢数字（〇〜九百九十九） */
  const KN = (n) => {
    const d = '〇一二三四五六七八九';
    if (!n) return '〇';
    const h = Math.floor(n / 100), t = Math.floor((n % 100) / 10), o = n % 10;
    return (h ? (h > 1 ? d[h] : '') + '百' : '') + (t ? (t > 1 ? d[t] : '') + '十' : '') + (o ? d[o] : '');
  };
  /** 原稿用紙で使うマス数（段落の初めの空き・段落の終わりの空きをふくむ） */
  const used = (ans, per = 20) => {
    let n = 0;
    String(ans).split('\n').forEach((p, k) => {
      if (k) n = Math.ceil(n / per) * per;
      n += Array.from(p).length;
    });
    return n;
  };
  /** 字数の注記 */
  const N = (ans, per = 20) => {
    const s = String(ans);
    return s.includes('\n') || s.startsWith('　')
      ? `（${KN(used(s, per))}マス・空きマスをふくむ）`
      : `（${KN(used(s, per))}字）`;
  };
